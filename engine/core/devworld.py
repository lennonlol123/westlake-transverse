def registration_of(salt: int):
    """这张图是哪次登记认证的；不在任何认证集合里 → None。"""
    for reg, cfg in REGISTRATIONS.items():
        if salt in cfg["maps"]:
            return reg
    return None


def pack_of(salt: int):
    reg = registration_of(salt)
    for p in (REGISTRATIONS[reg]["packs"] if reg else ()):
        if salt in p:
            return tuple(p)
    return None


