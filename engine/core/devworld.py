"""The configuration the development worlds were confirmed under, in one place.

A confirmed world is a (seed, salt) pair, and it is only that world under the
rotation and the tuning it was confirmed with. Building it under anything else
gives a different map with the same name -- which is the one mistake that would
invalidate every model run without failing anything.

So this module owns three things and nothing else:

    ROTATION   the five mechanics
    OVERLAY    the tuning that is CANDIDATE, not frozen
    CONFIRMED  the worlds, with the numbers they were confirmed at

Values that are FROZEN live in `adventure.TUNING` and deliberately do not
appear in `OVERLAY`: the deck ratio, momentum's ladder, momentum's boss gate,
and -- as of the boss sweep -- the boss's own four (`boss_hp_pct=125`,
`boss_stage_min=6`, `boss_wear_pct=70`, `boss_pool_exclude=("pierce",)`)
were settled and belong in one place.

`activate()` is not a context manager on purpose. It is called once by a CLI
entry point that then runs for hours, and a half-entered context that some
exception path leaves is exactly how a run ends up on the wrong map.
"""
