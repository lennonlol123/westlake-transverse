def pick_world_keys(n: int, start: int = 2, earlier=None) -> list[int]:
    """给 n 个新世界（身份第 3 版）依次挑最小的键，规则：
      1. 基础攻击和所有已有世界（含 A）都不同；
      2. 怪方五个机制指示槽（蓄力、守势、标记、模仿、封印）的代号，和每个已有世界相比最多 MECHANIC_SLOT_MAX_SAME 个同号。
    `earlier` = 已有世界的 identity_facts 列表（默认只有 A）；返回的键按挑出的顺序（升序）。"""
    taken = list(earlier) if earlier is not None else [identity_facts(9065, version=1)]
    keys = []
    key = start
    while len(keys) < n:
        f = identity_facts(key)
        ok = (f["atk"] not in {t["atk"] for t in taken}
              and all(sum(f["labels"][("them", m)] == t["labels"][("them", m)] for m in MECHANIC_SLOTS) <= MECHANIC_SLOT_MAX_SAME for t in taken))
        if ok:
            keys.append(key); taken.append(f)
        key += 1
        if key > 100000:
            raise ValueError("挑不到足够的世界键")
    return keys


